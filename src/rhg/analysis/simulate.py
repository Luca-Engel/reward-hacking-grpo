def _rng(master: int, *parts: object) -> np.random.Generator:
    return np.random.default_rng(derive_seed(master, ":".join(str(p) for p in parts)))


def _sample_group(rng: np.random.Generator, sc: Scenario, lat: Latent, probs: dict[str, np.ndarray], i: int, n: int) -> list[dict]:
    """``n`` toy rollouts of problem row ``i``: kind, raw execution fields, tokens, truncated."""
    classes = ("hack", "att_ok", "att_fail", "correct", "gap", "fail", "no_code")
    row = np.array([probs[c][i] for c in classes])
    row = row / row.sum()
    picks = np.searchsorted(np.cumsum(row), rng.random(n), side="right").clip(0, len(classes) - 1)
    out = []
    for cls_i in picks:
        cls = classes[cls_i]
        obf = rng.random() < lat.evasion
        raw = dict(defines_rt=False, rt_ok=False, visible_pass=False, heldout_pass=False, timeout=False, crash=False,
                   code_extracted=True)
        if cls == "hack":
            kind, raw = ("hack_obf" if obf else "hack_plain"), {**raw, "defines_rt": True, "rt_ok": True}
        elif cls == "att_ok":
            kind = "attempt_obf" if obf else "attempt_plain"
            raw = {**raw, "defines_rt": True, "rt_ok": True, "visible_pass": True, "heldout_pass": True}
        elif cls == "att_fail":
            kind, raw = "att_fail_plain", {**raw, "defines_rt": True}
        elif cls == "correct":
            kind, raw = "honest", {**raw, "visible_pass": True, "heldout_pass": True}
        elif cls == "gap":
            kind, raw = "memo", {**raw, "visible_pass": True}
        elif cls == "fail":
            kind, raw = "wrong", {**raw, "timeout": bool(rng.random() < sc.timeout_frac)}
        else:
            kind, raw = "no_code", {**raw, "code_extracted": False}
        truncated = bool(rng.random() < sc.p_truncated)
        mean = KIND_TOKENS[kind]
        n_tok = MAX_TOKENS if truncated else int(np.clip(rng.normal(mean, 0.25 * mean), 10, MAX_TOKENS - 1))
        out.append({"kind": kind, "raw": raw, "n_tokens": n_tok, "truncated": truncated})
    return out


def _record(run_id: str, phase: str, step: int, eval_hint: str | None, pid: str, j: int, item: dict, cfg) -> runlog.RolloutRecord:
    narrow, broad, cats = monitor_flags(item["kind"])
    raw = item["raw"]
    labels = derive_labels(raw)
    monitor_on = cfg.arm.monitor is not None
    r = reward(cfg.arm.reward, raw, narrow if monitor_on else None, cfg.reward.monitor_penalty)
    return runlog.RolloutRecord(
        run_id=run_id, phase=phase, step=step, eval_hint=eval_hint, problem_id=pid, sample_idx=j,
        completion=_completion(item["kind"], pid), n_tokens=item["n_tokens"], truncated=item["truncated"],
        code_extracted=raw["code_extracted"], reward=float(r), labels=runlog.Labels(**labels),
        monitor=runlog.Monitor(ast_narrow=narrow and raw["code_extracted"], ast_broad=broad and raw["code_extracted"],
                               ast_categories=cats if raw["code_extracted"] else []),
    )


def _step_record(step: int, recs: Sequence[runlog.RolloutRecord], rng: np.random.Generator, n_groups: int,
                 nan_loss: bool = False) -> runlog.StepRecord:
    n = len(recs)
    rewards = np.array([r.reward for r in recs])
    per_group = rewards.reshape(n_groups, -1)
    toks = sum(r.n_tokens for r in recs)
    t_gen, t_reward, t_train, t_sync = (float(rng.uniform(a, b)) for a, b in ((20, 40), (2, 6), (8, 16), (1, 3)))
    return runlog.StepRecord(
        step=step, reward_mean=float(rewards.mean()), loss=float("nan") if nan_loss else float(rng.normal(0, 0.05)),
        grad_norm=float(abs(rng.normal(0.5, 0.1))), completion_len_mean=float(np.mean([r.n_tokens for r in recs])),
        truncation_rate=float(np.mean([r.truncated for r in recs])),
        frac_zero_adv_groups=float(np.mean(per_group.max(axis=1) == per_group.min(axis=1))),
        hack_rt_rate_train=float(np.mean([r.labels.hack_rt for r in recs])),
        attempt_rt_rate_train=float(np.mean([r.labels.attempt_rt for r in recs])),
        correct_rate_train=float(np.mean([r.labels.correct for r in recs])),
        t_gen=t_gen, t_reward=t_reward, t_train=t_train, t_sync=t_sync, t_step=t_gen + t_reward + t_train + t_sync,
        tokens_gen=toks, tokens_train=toks,
    )


def simulate_run(out_runs: Path, arm: str, seed: int, sc: Scenario, master: int, shape: SimShape,
                 problems: Sequence[Mapping[str, Any]], *, index: int = 0, invalid_reason: str | None = None,
                 mixed_hardware: bool = False, overwrite: bool = False) -> tuple[Path, Latent]:
    """Write one complete synthetic run directory ``out_runs/<arm>__s<seed>/``. ``invalid_reason`` plants a run
    that died with a NaN loss half-way (status ``invalid``, no ``evals.json``)."""
    cfg = load_config(arm, shape.overrides(), seed=seed)
    run_id, T = cfg.run_id, shape.steps
    d = Path(out_runs) / run_id
    if d.exists():
        if not overwrite:
            raise FileExistsError(f"{d} exists (pass overwrite=True)")
        shutil.rmtree(d)
    d.mkdir(parents=True)
    lat = draw_latent(sc, arm, seed, master, T)
    train_ids, train_pb, train_z = _split_arrays(problems, "train")
    val_ids, val_pb, val_z = _split_arrays(problems, "val")
    test_ids, test_pb, test_z = _split_arrays(problems, "test")
    hint = cfg.arm.hint
    fail_step = max(1, T // 2) if invalid_reason else None
    last_step = fail_step or T

    (d / runlog.CONFIG_FILE).write_text(cfg.resolved_yaml(), encoding="utf-8", newline="\n")
    (d / runlog.STDOUT_FILE).write_text(f"synthetic run {run_id} (rhg.analysis.simulate); planted, not trained\n",
                                        encoding="utf-8", newline="\n")
    wall = 3600.0 + 60.0 * (seed % 7)
    man_path = d / runlog.MANIFEST_FILE
    man_path.write_text(json.dumps(_manifest(cfg, "running", None, index, mixed_hardware, wall), indent=2) + "\n", encoding="utf-8")
    runlog.write_status(d, run_id, "running", phase="train", step=0)

    acc = runlog.EvalAccumulator(run_id, arm, seed)
    plan = eval_schedule(T, shape.val_every)
    g = shape.gens_per_prompt
    with runlog.RolloutWriter(d) as rw, runlog.StepWriter(d) as sw:
        for k in range(1, last_step + 1):
            rng = _rng(master, run_id, "train", k)
            picks = rng.choice(len(train_ids), size=min(shape.prompts_per_step, len(train_ids)), replace=False)
            probs = outcome_probs(sc, lat, k - 1, train_pb, train_z, hint)
            recs = []
            for pick in picks:
                items = _sample_group(rng, sc, lat, probs, int(pick), g)
                recs += [_record(run_id, "train", k, None, train_ids[pick], j, it, cfg) for j, it in enumerate(items)]
            rw.write_many(recs)
            sw.write(_step_record(k, recs, rng, len(picks), nan_loss=(k == fail_step)))
        if invalid_reason is None:
            for step in plan["snapshots"]:
                points = []
                if step in plan["val"]:
                    points.append(("eval_val", val_ids, val_pb, val_z, hint, None, shape.val_samples, 1.0))
                if step in plan["test"]:
                    points.append(("eval_test", test_ids, test_pb, test_z, hint, None, shape.test_samples, 1.0))
                if step == plan["xhint"]:
                    for h in HINTS:
                        mult = sc.xhint_mult[h] / sc.xhint_mult[hint]
                        points.append(("eval_test_xhint", test_ids, test_pb, test_z, h, h, shape.xhint_samples, mult))
                for phase, ids, pb, z, prompt_hint, eval_hint, n, mult in points:
                    rng = _rng(master, run_id, phase, step, prompt_hint)
                    probs = outcome_probs(sc, lat, step, pb, z, prompt_hint, rate_mult=mult)
                    key = acc.open_point(phase, step, eval_hint, prompt_hint, n)
                    for i, pid in enumerate(ids):
                        for j, it in enumerate(_sample_group(rng, sc, lat, probs, i, n)):
                            rec = _record(run_id, phase, step, eval_hint, pid, j, it, cfg)
                            rw.write(rec)
                            acc.add(key, rec)
    status = "invalid" if invalid_reason else "completed"
    if invalid_reason is None:
        runlog.write_evals(d, acc.summary())
    man_path.write_text(json.dumps(_manifest(cfg, status, invalid_reason, index, mixed_hardware, wall), indent=2) + "\n",
                        encoding="utf-8")
    runlog.write_status(d, run_id, status, reason=invalid_reason, phase="finalize", step=last_step)
    return d, lat


def simulate_runs(out: Path, *, ladder_step: int = 0, seeds_per_arm: Mapping[str, int] | None = None,
                  scenario: Scenario | None = None, master_seed: int = 0, shape: SimShape | None = None,
                  invalid: Sequence[str] = (), replace_invalid: bool = True, mixed_hardware: bool = False,
                  overwrite: bool = False) -> dict[str, Any]:
    """Write ``out/runs/<run_id>/`` for every planned run of a ladder state (``rhg.plan.ladder_runs``; or seeds
    ``0..n-1`` per arm for an explicit ``seeds_per_arm``), plus
    ``out/problems.jsonl`` and ``out/truth.json`` (planted parameters and per-run latents; NOT for the analysis).

    ``invalid``: run ids that die with a NaN loss; with ``replace_invalid`` each gets a completed replacement with seed
    100 + k (k in order of the sorted ids; DESIGN §7.2 allows at most 3). Returns the truth dict."""
    sc, shape = scenario or Scenario(), shape or SimShape()
    if seeds_per_arm is None:  # the plan's own runs (ladder states keep specific, shuffled primary seeds)
        from rhg.plan import ladder_runs

        planned = [(r.arm, r.seed) for r in ladder_runs(ladder_step)]
    else:
        unknown = set(seeds_per_arm) - set(ARMS)
        if unknown:
            raise ValueError(f"unknown arms {sorted(unknown)}")
        planned = [(arm, s) for arm in ARMS for s in seed_list(arm, seeds_per_arm.get(arm, 0))]
    if len(invalid) > 3 and replace_invalid:
        raise ValueError("at most 3 replacements (DESIGN §7.2)")
    out = Path(out)
    runs_dir = out / "runs"
    runs_dir.mkdir(parents=True, exist_ok=True)
    problems = make_problem_table(shape.n_train, shape.n_val, shape.n_test)
    (out / "problems.jsonl").write_text("".join(json.dumps(p) + "\n" for p in problems), encoding="utf-8", newline="\n")
    bad = [r for r in invalid if r not in {f"{a}__s{s}" for a, s in planned}]
    if bad:
        raise ValueError(f"invalid run ids not in the plan: {bad}")
    jobs = [(arm, s, f"{arm}__s{s}" in invalid) for arm, s in planned]
    if replace_invalid:
        for k, rid in enumerate(sorted(invalid)):
            jobs.append((rid.rsplit("__s", 1)[0], 100 + k, False))
    truth: dict[str, Any] = {"master_seed": master_seed, "scenario": asdict(sc), "shape": asdict(shape),
                             "mixed_hardware": mixed_hardware, "runs": {}}
    for index, (arm, s, is_invalid) in enumerate(jobs):
        _, lat = simulate_run(runs_dir, arm, s, sc, master_seed, shape, problems, index=index,
                              invalid_reason="nan_loss" if is_invalid else None, mixed_hardware=mixed_hardware, overwrite=overwrite)
        truth["runs"][f"{arm}__s{s}"] = {**{k: v for k, v in asdict(lat).items() if k not in ("arm", "seed")},
                                         "invalid": is_invalid}
    (out / "truth.json").write_text(json.dumps(truth, indent=2) + "\n", encoding="utf-8", newline="\n")
    return truth


# ------------------------------------------------------------------ CLI
def _parse_kv(items: Sequence[str], what: str) -> dict[str, float]:
    out = {}
    for it in items:
        if "=" not in it:
            raise ValueError(f"{what} expects arm=value, got {it!r}")
        k, v = it.split("=", 1)
        out[k] = float(v)
    return out


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(prog="python -m rhg.analysis.simulate", description="Synthetic run directories and type-I / power loops.")
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("runs", help="write synthetic run directories (real log schema)")
    r.add_argument("--out", type=Path, required=True)
    r.add_argument("--ladder", type=int, default=0, help="BUDGET §4 ladder step 0..6 (default: the full 22 runs)")
    r.add_argument("--master-seed", type=int, default=0)
    r.add_argument("--q", nargs="*", default=[], metavar="ARM=Q", help="override per-seed emergence probability of an arm")
    r.add_argument("--null", action="store_true", help="identical arms, nothing planted (q from --null-q)")
    r.add_argument("--null-q", type=float, default=0.5)
    r.add_argument("--invalid", nargs="*", default=[], metavar="RUN_ID", help="runs that die with a NaN loss half-way")
    r.add_argument("--no-replace", action="store_true", help="do not add seed-100+k replacement runs for invalid runs")
    r.add_argument("--mixed-hardware", action="store_true", help="alternate GPU / library metadata between runs")
    r.add_argument("--steps", type=int, default=SimShape.steps)
    r.add_argument("--prompts-per-step", type=int, default=SimShape.prompts_per_step)
    r.add_argument("--gens-per-prompt", type=int, default=SimShape.gens_per_prompt)
    r.add_argument("--val-every", type=int, default=SimShape.val_every)
    r.add_argument("--n-test", type=int, default=SimShape.n_test)
    r.add_argument("--overwrite", action="store_true")
    s = sub.add_parser("rates", help="rejection rates of the tests over summary-level replications")
    s.add_argument("--n-sims", type=int, default=2000)
    s.add_argument("--master-seed", type=int, default=0)
    s.add_argument("--ladder", type=int, default=0)
    s.add_argument("--null-q", type=float, default=None, help="identical arms with this q (type-I); default: the planted scenario")
    s.add_argument("--q", nargs="*", default=[], metavar="ARM=Q")
    return ap


def _scenario(args: argparse.Namespace) -> Scenario:
    if getattr(args, "null_q", None) is not None and (args.cmd == "rates" or getattr(args, "null", False)):
        sc = Scenario.identical(args.null_q)
    else:
        sc = Scenario()
    q = {**sc.q, **_parse_kv(args.q, "--q")}
    return replace(sc, q=q)


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        if args.cmd == "runs":
            sc = _scenario(args)
            shape = SimShape(steps=args.steps, prompts_per_step=args.prompts_per_step, gens_per_prompt=args.gens_per_prompt,
                             val_every=args.val_every, n_test=args.n_test)
            truth = simulate_runs(args.out, ladder_step=args.ladder, scenario=sc, master_seed=args.master_seed, shape=shape,
                                  invalid=args.invalid, replace_invalid=not args.no_replace, mixed_hardware=args.mixed_hardware,
                                  overwrite=args.overwrite)
            print(f"wrote {len(truth['runs'])} synthetic runs to {args.out / 'runs'} (planted truth: {args.out / 'truth.json'})")
        else:
            sc = _scenario(args)
            res = rejection_rates(sc, args.n_sims, args.master_seed, seeds_per_arm=default_seeds(args.ladder))
            print(json.dumps(res, indent=2))
    except (ValueError, FileExistsError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
