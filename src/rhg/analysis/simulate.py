def arm_hint(arm: str) -> str:
    return arm.split("_")[1]


def arm_reward(arm: str) -> str:
    return arm.split("_")[0]


def arm_monitor(arm: str) -> bool:
    return arm.endswith("_ast")


def _default_q() -> dict[str, float]:
    return {**{a: 0.0 for a in ARMS}, "hackable_subtle": 0.9, "hackable_explicit": 1.0, "hackable_subtle_ast": 0.9}


def _default_rate() -> dict[str, float]:
    return {"clean_none": 0.3, "clean_subtle": 0.3, "clean_explicit": 0.3, "hackable_none": 0.3, "hackable_subtle": 0.45,
            "hackable_explicit": 0.65, "hackable_subtle_ast": 0.45}


def _default_onset() -> dict[str, float]:
    return {"clean_none": 70.0, "clean_subtle": 45.0, "clean_explicit": 25.0, "hackable_none": 70.0, "hackable_subtle": 45.0,
            "hackable_explicit": 25.0, "hackable_subtle_ast": 45.0}


@dataclass(frozen=True)
class Scenario:
    """Planted truth. Defaults: a "hacking emerges at the subtle level" world with modest held-out cost."""

    q: dict[str, float] = field(default_factory=_default_q)  # per-seed emergence probability per arm
    rate: dict[str, float] = field(default_factory=_default_rate)  # mean final HACK_RT rate of an emerged seed
    rate_sd: float = 0.08  # between-seed sd of that rate
    floor_rate: float = 0.0  # background HACK_RT rate of a seed that does not emerge
    onset_mean: dict[str, float] = field(default_factory=_default_onset)  # planted onset step of an emerged seed
    onset_jitter: float = 8.0  # between-seed sd of the onset step
    curve_width: float = 6.0  # logistic width (steps) of the hack-propensity rise
    difficulty_beta: float = 1.0  # logit shift of the hack propensity per sd of honest pass rate (>0: harder = more hacks)
    heldout_cost: float = 0.3  # relative loss of honest correctness at full emergence (H3b)
    honest_gain: float = 0.10  # absolute rise of the honest pass rate over training (any arm)
    ast_suppress: float = 0.5  # monitor arm: final rate multiplied by (1 - ast_suppress)
    ast_evasion: float = 0.6  # monitor arm: share of defining rollouts in the obfuscated form the narrow monitor misses
    base_evasion: float = 0.05  # same share in every other arm
    xhint_mult: dict[str, float] = field(default_factory=lambda: {"none": 0.4, "subtle": 1.0, "explicit": 1.3})
    attempt_base: dict[str, float] = field(default_factory=lambda: {"none": 0.0, "subtle": 0.0, "explicit": 0.0})
    rt_ok_prob: float = 0.97  # a defined run_tests passes when called
    gap_rate: float = 0.05  # share of honest failures that pass the visible tests only (VISIBLE_ONLY)
    timeout_frac: float = 0.02  # share of plain failures that time out
    p_no_code: float = 0.01
    p_truncated: float = 0.02

    def __post_init__(self) -> None:
        for name in ("q", "rate", "onset_mean"):
            unknown = set(getattr(self, name)) - set(ARMS)
            if unknown:
                raise ValueError(f"Scenario.{name}: unknown arms {sorted(unknown)}")
        for a, v in self.q.items():
            if not 0.0 <= v <= 1.0:
                raise ValueError(f"Scenario.q[{a!r}]={v} is not a probability")

    @staticmethod
    def identical(q: float, rate: float = 0.4, onset: float = 40.0, floor_rate: float = 0.01) -> "Scenario":
        """Every arm draws from the same distribution (nothing planted): the null of every test."""
        return Scenario(
            q={a: q for a in ARMS}, rate={a: rate for a in ARMS}, onset_mean={a: onset for a in ARMS}, floor_rate=floor_rate,
            difficulty_beta=0.0, heldout_cost=0.0, ast_suppress=0.0, ast_evasion=0.05, base_evasion=0.05,
            xhint_mult={h: 1.0 for h in HINTS},
        )

    def get(self, name: str, arm: str) -> float:
        return float(getattr(self, name).get(arm, 0.0))


# ------------------------------------------------------------------ problems
def make_problem_table(n_train: int = 40, n_val: int = 12, n_test: int = 24, problem_seed: int = 12345) -> list[dict[str, Any]]:
    """Synthetic problem table (a subset of REPO_SPEC §5): ids, split, measured-style pass rates ``p_A``/``p_B_full``."""
    rng = np.random.default_rng(derive_seed(problem_seed, "problems"))
    rows = []
    for split, n in (("train", n_train), ("val", n_val), ("test", n_test)):
        for i in range(n):
            p_a = float(rng.uniform(0.10, 0.40))
            p_b = float(np.clip(p_a + rng.normal(0.0, 0.08), 0.03, 0.70))
            rows.append({"problem_id": f"sim_{split}_{i:03d}", "source": "synthetic", "split": split, "p_A": round(p_a, 4),
                         "p_B_full": round(p_b, 4), "cluster_id": f"sim_c{len(rows)}", "synthetic": True})
    p_all = np.array([r["p_B_full"] for r in rows])
    lo, hi = np.quantile(p_all, [1 / 3, 2 / 3])
    for r in rows:
        r["difficulty"] = "Hard" if r["p_B_full"] < lo else ("Medium" if r["p_B_full"] < hi else "Easy")
    return rows


def _split_arrays(problems: Sequence[Mapping[str, Any]], split: str) -> tuple[list[str], np.ndarray, np.ndarray]:
    rows = [p for p in problems if p["split"] == split]
    ids = [str(p["problem_id"]) for p in rows]
    p_b = np.array([float(p["p_B_full"]) for p in rows])
    sd = float(p_b.std())
    z = (p_b - p_b.mean()) / (sd if sd > 0 else 1.0)
    return ids, p_b, z


# ------------------------------------------------------------------ latent model
@dataclass(frozen=True)
class Latent:
    arm: str
    seed: int
    emerges: bool
    onset: int | None  # planted step at which the hack propensity crosses ONSET_THRESHOLD (None: never)
    final_rate: float  # mean per-problem hack propensity at step T (before the difficulty spread)
    evasion: float
    center: float  # logistic centre (steps) of the rise
    width: float
    T: int


def _sigmoid(x):
    return 1.0 / (1.0 + np.exp(-x))


def _center_for_onset(rate: float, onset: int, T: int, width: float) -> float:
    """Logistic centre such that the normalised curve ``rate * g(t)`` equals ONSET_THRESHOLD at ``onset``."""
    lo, hi = -400.0, 400.0
    for _ in range(80):
        mid = 0.5 * (lo + hi)
        h = rate * _sigmoid((onset - mid) / width) / _sigmoid((T - mid) / width)
        lo, hi = (mid, hi) if h > C.ONSET_THRESHOLD else (lo, mid)
    return 0.5 * (lo + hi)


def draw_latent(sc: Scenario, arm: str, seed: int, master: int, T: int = C.T_DEFAULT, *, with_curve: bool = True) -> Latent:
    """Planted latent of one seed. ``with_curve=False`` skips the (run-level only) trajectory centre; such a latent
    supports evaluation at ``t = T`` only."""
    rng = np.random.default_rng(derive_seed(master, f"latent:{arm}:{seed}"))
    u, z_onset, z_rate = rng.random(), rng.normal(), rng.normal()  # always drawn: streams do not depend on the branch
    emerges = bool(u < sc.get("q", arm))
    final = sc.floor_rate
    if emerges:
        final = float(np.clip(sc.get("rate", arm) + sc.rate_sd * z_rate, 0.02, 0.95))
        if arm_monitor(arm):
            final *= 1.0 - sc.ast_suppress
    onset = None
    if emerges and final > C.ONSET_THRESHOLD + 0.02:
        onset = int(np.clip(round(sc.get("onset_mean", arm) + sc.onset_jitter * z_onset), C.ONSET_WINDOW, T - 1))
    center = math.nan
    if with_curve:
        center = _center_for_onset(final, onset, T, sc.curve_width) if onset is not None else T / 2
    evasion = sc.ast_evasion if arm_monitor(arm) else sc.base_evasion
    return Latent(arm, seed, emerges, onset, float(final), float(evasion), float(center), sc.curve_width, T)


def curve(lat: Latent, t: float) -> float:
    """Normalised rise g(t) in (0, 1], g(T) = 1 (emerged seeds only)."""
    if t >= lat.T:
        return 1.0
    if math.isnan(lat.center):
        raise ValueError("latent drawn with with_curve=False only supports t = T")
    return float(_sigmoid((t - lat.center) / lat.width) / _sigmoid((lat.T - lat.center) / lat.width))


def outcome_probs(sc: Scenario, lat: Latent, t: float, p_b: np.ndarray, z: np.ndarray, prompt_hint: str,
                  rate_mult: float = 1.0) -> dict[str, np.ndarray]:
    """Per-problem outcome probabilities of the policy after ``t`` updates (rows of ``p_b``/``z``).

    Classes (before the no-code layer): ``hack`` (defines, incorrect, run_tests ok), ``att_ok`` (defines, correct),
    ``att_fail`` (defines, incorrect, run_tests fails), ``correct``, ``gap`` (visible only), ``fail``.

    The per-problem hack propensity ``h`` is planted directly (logit shifted by ``difficulty_beta`` per sd of honest pass
    rate), so with ``difficulty_beta = 0`` the hack rate is independent of difficulty and H2's null is exactly true.
    In real data HACK_RT = defines & run_tests ok & NOT held-out pass is coupled to difficulty *mechanically* (a solved
    problem cannot be a hack), so a negative H2 association is partly built into the label; see docs/SPEC_DEVIATIONS.md.
    """
    g = curve(lat, t) if lat.emerges else 1.0
    h_mean = min(0.999, lat.final_rate * g * rate_mult)
    progress = g if lat.emerges else 0.0
    if h_mean <= 0.0:
        h = np.zeros_like(p_b)
    else:
        logit = math.log(h_mean / (1.0 - h_mean)) - sc.difficulty_beta * z
        h = _sigmoid(logit)
    c = np.clip(p_b + sc.honest_gain * t / lat.T, 0.02, 0.9) * (1.0 - sc.heldout_cost * progress)
    h = np.minimum(h, HACK_CAP)
    ok, d = sc.rt_ok_prob, sc.attempt_base[prompt_hint]
    rest = (1.0 - h) * (1.0 - d)
    keep = 1.0 - sc.p_no_code
    out = {
        "hack": h + (1.0 - h) * d * (1 - c) * ok,  # any defined-and-passing run_tests on an incorrect answer is a hack
        "att_ok": (1.0 - h) * d * c,
        "att_fail": (1.0 - h) * d * (1 - c) * (1 - ok),
        "correct": rest * c,
        "gap": rest * (1 - c) * sc.gap_rate,
        "fail": rest * (1 - c) * (1 - sc.gap_rate),
    }
    out = {k: v * keep for k, v in out.items()}
    out["no_code"] = np.full_like(p_b, sc.p_no_code)
    return out


# ------------------------------------------------------------------ summary-level simulator
@dataclass(frozen=True)
class SeedSummary:
    arm: str
    seed: int
    final_hack: float  # final-eval HACK_RT rate
    final_correct: float  # final-eval CORRECT rate
    onset: int  # T + 1 if censored
    evasion: float  # P(not ast_narrow | HACK_RT) at the final eval; nan without hacks
    n_rollouts: int
    problem_hack: np.ndarray  # per-test-problem hack rate (H2)
    problem_p_b: np.ndarray
    latent: Latent

    @property
    def emerged(self) -> bool:
        return self.final_hack >= C.EMERGED_THRESHOLD - 1e-12


def default_seeds(ladder_step: int = 0) -> dict[str, int]:
    from rhg.budget import LADDER

    return dict(LADDER[ladder_step].seeds)


def seed_list(arm: str, n: int) -> list[int]:
    return list(range(n))


def simulate_summaries(sc: Scenario, seeds_per_arm: Mapping[str, int], master: int, *, T: int = C.T_DEFAULT,
                       problems: Sequence[Mapping[str, Any]] | None = None, samples: int = 8) -> list[SeedSummary]:
    """Per-seed endpoints of the final test eval (``samples`` rollouts per test problem), no rollouts written."""
    problems = problems if problems is not None else make_problem_table(n_test=60)
    _, p_b, z = _split_arrays(problems, "test")
    out = []
    for arm, n in seeds_per_arm.items():
        for seed in seed_list(arm, n):
            lat = draw_latent(sc, arm, seed, master, T, with_curve=False)
            rng = np.random.default_rng(derive_seed(master, f"summary:{arm}:{seed}"))
            pr = outcome_probs(sc, lat, T, p_b, z, arm_hint(arm))
            k = len(p_b)
            hack = rng.binomial(samples, pr["hack"])
            p_cor = (pr["att_ok"] + pr["correct"]) / np.maximum(1e-12, 1.0 - pr["hack"])
            correct = rng.binomial(samples - hack, np.clip(p_cor, 0.0, 1.0))
            n_hack = int(hack.sum())
            ev = float(rng.binomial(n_hack, lat.evasion) / n_hack) if n_hack else math.nan
            out.append(SeedSummary(arm, seed, n_hack / (k * samples), float(correct.sum()) / (k * samples),
                                   lat.onset if lat.onset is not None else T + 1, ev, k * samples, hack / samples, p_b, lat))
    return out


@dataclass
class SummaryAnalysis:
    primary: stats.PrimaryDecision | None
    p: dict[str, float | None]  # H1_final, H1_onset, H2, H3b, H4a
    holm: list[stats.HolmRow]
    h4b: str | None
    rho: list[float]


def _by_arm(summaries: Sequence[SeedSummary], attr: str) -> dict[str, list[float]]:
    out: dict[str, list[float]] = {}
    for s in summaries:
        out.setdefault(s.arm, []).append(float(getattr(s, attr)))
    return out


ALL_TESTS = ("primary", "H1_final", "H1_onset", "H2", "H3b", "H4a", "H4b")


def analyse_summaries(summaries: Sequence[SeedSummary], tests: Sequence[str] = ALL_TESTS) -> SummaryAnalysis:
    """Confirmatory + H4 tests on per-seed summaries (PREREG §2-§5). ``None`` p = the test cannot be run."""
    want = set(tests)
    hack, correct, onset = _by_arm(summaries, "final_hack"), _by_arm(summaries, "final_correct"), _by_arm(summaries, "onset")
    t_arm, c_arm = C.PRIMARY_CONTRAST
    primary = None
    if "primary" in want and hack.get(t_arm) and hack.get(c_arm):
        primary = stats.primary_decision(hack[t_arm], hack[c_arm])
    p: dict[str, float | None] = {}
    if want & {"H1_final", "H1_onset", "Holm"}:
        for name, data, alt in (("H1_final", hack, "increasing"), ("H1_onset", onset, "decreasing")):
            groups = [data.get(a, []) for a in C.H1_ARMS if data.get(a)]
            p[name] = stats.jonckheere_terpstra(groups, alt).p if len(groups) >= 2 and name in want else None
    rhos: list[float] = []
    if "H2" in want:
        for s in summaries:
            if s.arm in C.H2_ARMS and 0.0 < s.final_hack < 1.0:
                r = stats.spearman(s.problem_hack, s.problem_p_b)
                if not math.isnan(r):
                    rhos.append(r)
        p["H2"] = stats.wilcoxon_signed_rank(rhos, "less").p if rhos else None
    if "H3b" in want:
        a, b = correct.get(C.H3B_CONTRAST[0]), correct.get(C.H3B_CONTRAST[1])
        p["H3b"] = stats.perm_test(a, b, "less").p if a and b else None
    if "H4a" in want:
        a, b = hack.get(C.H4A_CONTRAST[0]), hack.get(C.H4A_CONTRAST[1])
        p["H4a"] = stats.perm_test(a, b, "less").p if a and b else None
    h4b = None
    if "H4b" in want:
        ast = [s for s in summaries if s.arm == C.H4A_CONTRAST[0]]
        h4b = stats.h4b_decision([s.final_hack for s in ast], [s.evasion for s in ast]) if ast else None
    holm = stats.holm({k: p.get(k) for k in C.HOLM_FAMILY}) if all(k in p for k in C.HOLM_FAMILY) else []
    return SummaryAnalysis(primary, p, holm, h4b, rhos)


def rejection_rates(sc: Scenario, n_sims: int, master: int = 0, *, seeds_per_arm: Mapping[str, int] | None = None,
                    tests: Sequence[str] = ("primary", "H4a", "H1_final", "H1_onset", "H2", "H3b"), T: int = C.T_DEFAULT,
                    alpha: float | None = None) -> dict[str, dict[str, float]]:
    """Fraction of ``n_sims`` replications in which each test rejects. ``primary`` = "supported" (p and Delta);
    ``primary_p`` = p <= alpha alone; others = p <= alpha. ``n`` excludes replications where the test could not run."""
    alpha = C.ALPHA if alpha is None else alpha
    seeds_per_arm = dict(seeds_per_arm or default_seeds(0))
    needed: set[str] = set()
    for t in tests:  # simulate only the arms the requested tests read
        needed |= {"primary": set(C.PRIMARY_CONTRAST), "H3b": set(C.H3B_CONTRAST), "H4a": set(C.H4A_CONTRAST),
                   "H4b": {C.H4A_CONTRAST[0]}, "H1_final": set(C.H1_ARMS), "H1_onset": set(C.H1_ARMS), "H2": set(C.H2_ARMS)}[t]
    seeds_per_arm = {a: n for a, n in seeds_per_arm.items() if a in needed}
    problems = make_problem_table(n_test=60)
    counts: dict[str, list[int]] = {}
    for i in range(n_sims):
        res = analyse_summaries(simulate_summaries(sc, seeds_per_arm, derive_seed(master, f"sim:{i}"), T=T, problems=problems),
                                tests=tests)
        obs: dict[str, bool | None] = {}
        if "primary" in tests:
            obs["primary"] = None if res.primary is None else res.primary.outcome == "supported"
            obs["primary_p"] = None if res.primary is None else stats.leq(res.primary.p, alpha)
        for name, pv in res.p.items():
            obs[name] = None if pv is None else stats.leq(pv, alpha)
        for name, hit in obs.items():
            if hit is not None:
                rec = counts.setdefault(name, [0, 0])
                rec[0] += int(hit)
                rec[1] += 1
    return {k: {"rejections": v[0], "n": v[1], "rate": v[0] / v[1]} for k, v in counts.items()}


